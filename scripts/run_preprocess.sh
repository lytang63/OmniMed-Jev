#!/bin/bash
# Run `omnimedjev preprocess` over the converted dataset tree, with start/stop
# via a pidfile.
#
# WHY the `json_paths` override: `find_question_jsons` does a recursive glob
# over the whole input tree, and that tree holds hundreds of thousands of PNGs
# next to the question JSONs. On a network filesystem the walk takes tens of
# minutes. `preprocess` already accepts a `json_paths` list, so this script
# globs the 48 question files itself and passes them explicitly — no engine
# patch needed, the override is an existing extension point.
#
# WHY a pidfile and not pgrep: a caller's command line routinely contains this
# script's own name, so `pgrep -f` matches the caller's shell and kills it.
#
# Usage:
#   ./scripts/run_preprocess.sh start [args...]   # default args shown below
#   ./scripts/run_preprocess.sh stop
#   ./scripts/run_preprocess.sh status
set -uo pipefail

PROJECT_ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$PROJECT_ROOT" || exit 1
LOGS="${PROJECT_ROOT}/datas/logs"
PIDFILE="${LOGS}/preprocess.pid"
CONVERTED="${CONVERTED:-${PROJECT_ROOT}/datas/converted/omnimed-suite}"
OUTPUT_DIR="${OUTPUT_DIR:-${PROJECT_ROOT}/datas/preprocessed}"
JSON_PATHS="${JSON_PATHS:-${LOGS}/json_paths.yaml}"
OUT_LOG="${LOGS}/preprocess_full.log"
mkdir -p "$LOGS"

# Collect the question JSONs and write the yaml `preprocess` consumes.
write_json_paths() {
  mkdir -p "$(dirname "$JSON_PATHS")"
  {
    echo "# Generated by scripts/run_preprocess.sh"
    echo "# The images are already PNGs, so archive extraction has nothing to do;"
    echo "# skipping it avoids a second full-tree walk."
    echo "no_extract_archives: true"
    echo "no_hf_dataset: false"
    # No `tasks:` key, so `preprocess` emits every family the converted tree
    # carries. That pool is what the task-balanced draw below samples from; the
    # four decision families are selected afterwards, by uid.
    echo "json_paths:"
    find "$CONVERTED" -name '*_questions_*.json' | sort | sed 's/^/  - "/; s/$/"/'
  } > "$JSON_PATHS"
  echo "wrote $(grep -c '^  - ' "$JSON_PATHS") json_paths -> $JSON_PATHS"
}

case "${1:-status}" in
  start)
    shift
    if [[ -r "$PIDFILE" ]] && kill -0 "$(cat "$PIDFILE")" 2>/dev/null; then
      echo "already running: pid $(cat "$PIDFILE")" >&2
      exit 1
    fi
    if [[ ! -d "$CONVERTED" ]]; then
      echo "missing $CONVERTED — run scripts/convert_datasets.py first" >&2
      exit 1
    fi
    write_json_paths
    nohup bash -c "
      source '${PROJECT_ROOT}/scripts/env.sh'
      cd '${PROJECT_ROOT}'
      exec python -u -m omnimedjev \
        -n preprocess -d omnimed-suite --config local \
        --root_dir '${PROJECT_ROOT}' \
        --input_dir '${PROJECT_ROOT}/datas/converted' \
        --output_dir '${OUTPUT_DIR}' \
        --custom_args '${JSON_PATHS}' \
        preprocess
    " > "$OUT_LOG" 2>&1 &
    echo $! > "$PIDFILE"
    echo "started pid $(cat "$PIDFILE") -> $OUT_LOG"
    ;;
  stop)
    if [[ -r "$PIDFILE" ]]; then
      p="$(cat "$PIDFILE")"
      if kill -0 "$p" 2>/dev/null; then kill "$p" && echo "stopped pid $p"; else echo "pid $p not alive"; fi
      rm -f "$PIDFILE"
    else
      echo "no pidfile"
    fi
    ;;
  status)
    if [[ -r "$PIDFILE" ]] && kill -0 "$(cat "$PIDFILE")" 2>/dev/null; then
      echo "running: pid $(cat "$PIDFILE")"
    else
      echo "not running"
    fi
    echo "loaded JSONs so far: $(grep -ac 'Loaded' "$OUT_LOG" 2>/dev/null || echo 0)"
    gzip -c "$OUT_LOG" 2>/dev/null | tail -c 400 2>/dev/null | gunzip 2>/dev/null | tr '\r' '\n' | tail -3
    ;;
  *)
    echo "usage: $0 {start|stop|status}" >&2; exit 1 ;;
esac
